    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        try {
            String codigo = txtCodigo.getText().trim();

            if (codigo.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this, "Ingrese el código del cliente que desea consultar");
                return;
            }

            Cliente cliente = clienteController.buscarCliente(codigo);

            txtNombre.setText(cliente.getNombreCompleto());
            txtIdentidad.setText(cliente.getIdentidad());
            txtTelefono.setText(cliente.getTelefono());
            txtDireccion.setText(cliente.getDireccion());

        } catch (ClienteNoEncontradoException e) {
            JOptionPane.showMessageDialog(
                    this, "El cliente con ese código no existe");
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        try {
            String codigo = txtCodigo.getText().trim();
            String nombre = txtNombre.getText().trim();
            String identidad = txtIdentidad.getText().trim();
            String telefono = txtTelefono.getText().trim();
            String direccion = txtDireccion.getText().trim();

            if (codigo.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this, "Ingrese el código del cliente que desea modificar");
                return;
            }

            Cliente cliente = clienteController.buscarCliente(codigo);

            if (nombre.isEmpty() || identidad.isEmpty()
                    || telefono.isEmpty() || direccion.isEmpty()) {

                JOptionPane.showMessageDialog(
                        this, "Todos los campos son obligatorios");
                return;
            }

            int respuesta = JOptionPane.showConfirmDialog(
                    this,
                    "¿Está seguro de modificar este cliente?",
                    "Confirmar modificación",
                    JOptionPane.YES_NO_OPTION
            );

            if (respuesta == JOptionPane.YES_OPTION) {
                clienteController.modificarCliente(
                        codigo, nombre, identidad, telefono, direccion);

                JOptionPane.showMessageDialog(
                        this, "Cliente modificado correctamente");

                limpiarCampos();
                cargarTabla();
            }

        } catch (ClienteNoEncontradoException e) {
            JOptionPane.showMessageDialog(
                    this, "El cliente con ese código no existe");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

