    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
            String codigo = txtCodigo.getText().trim();
            String descripcion = txtDescripcion.getText().trim();
            String precioTexto = txtPrecioBase.getText().trim();
            String tiempoTexto = txtTiempoEstimado.getText().trim();

            if (codigo.isEmpty() || descripcion.isEmpty()
                    || precioTexto.isEmpty() || tiempoTexto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete todos los campos");
                return;
            }

            double precio = Double.parseDouble(precioTexto);
            int tiempo = Integer.parseInt(tiempoTexto);

            if (precio <= 0) {
                JOptionPane.showMessageDialog(this, "El precio debe ser positivo");
                return;
            }

            if (tiempo <= 0) {
                JOptionPane.showMessageDialog(this, "El tiempo debe ser positivo");
                return;
            }

            servicioController.registrarServicio(codigo, descripcion, precio, tiempo);

            JOptionPane.showMessageDialog(this, "Servicio registrado correctamente");

            limpiarCampos();
            cargarTabla();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos");
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el código del servicio");
            return;
        }

        Servicio servicio = servicioController.buscarServicio(codigo);

        if (servicio == null) {
            JOptionPane.showMessageDialog(this, "El servicio no existe");
            return;
        }

        txtDescripcion.setText(servicio.getDescripcion());
        txtPrecioBase.setText(String.valueOf(servicio.getPrecioBase()));
        txtTiempoEstimado.setText(String.valueOf(servicio.getTiempoEstimado()));
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        try {
            String codigo = txtCodigo.getText().trim();

            if (codigo.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese el código del servicio");
                return;
            }

            Servicio servicio = servicioController.buscarServicio(codigo);

            if (servicio == null) {
                JOptionPane.showMessageDialog(this, "El servicio no existe");
                return;
            }

            String descripcion = txtDescripcion.getText().trim();
            String precioTexto = txtPrecioBase.getText().trim();
            String tiempoTexto = txtTiempoEstimado.getText().trim();

            if (descripcion.isEmpty() || precioTexto.isEmpty() || tiempoTexto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete todos los campos");
                return;
            }

            int confirmar = JOptionPane.showConfirmDialog(
                    this,
                    "¿Desea modificar este servicio?",
                    "Confirmar modificación",
                    JOptionPane.YES_NO_OPTION
            );

            if (confirmar != JOptionPane.YES_OPTION) {
                return;
            }

            double precio = Double.parseDouble(precioTexto);
            int tiempo = Integer.parseInt(tiempoTexto);

            if (precio <= 0 || tiempo <= 0) {
                JOptionPane.showMessageDialog(this, "El precio y el tiempo deben ser positivos");
                return;
            }

            servicioController.modificarServicio(codigo, descripcion, precio, tiempo);

            JOptionPane.showMessageDialog(this, "Servicio modificado correctamente");

            limpiarCampos();
            cargarTabla();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos");
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el código del servicio");
            return;
        }

        Servicio servicio = servicioController.buscarServicio(codigo);

        if (servicio == null) {
            JOptionPane.showMessageDialog(this, "El servicio no existe");
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar este servicio?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {
            try {
                servicioController.eliminarServicio(codigo);

                JOptionPane.showMessageDialog(this,
                        "Servicio eliminado correctamente");

                limpiarCampos();
                cargarTabla();

            } catch (IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

