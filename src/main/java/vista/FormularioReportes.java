    private class GraficoIngresos extends JPanel {

        private Map<String, Double> datos = new HashMap<>();

        public void setDatos(Map<String, Double> datos) {
            this.datos = datos;
            repaint();
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);

            Graphics2D g2 = (Graphics2D) g;
            g2.setRenderingHint(
                    RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON
            );

            if (datos.isEmpty()) {
                g2.drawString("No hay ingresos registrados", 20, 30);
                return;
            }

            double maximo = 0;

            for (double valor : datos.values()) {
                if (valor > maximo) {
                    maximo = valor;
                }
            }

            if (maximo == 0) {
                g2.drawString("No hay ingresos registrados", 20, 30);
                return;
            }

            int ancho = getWidth();
            int alto = getHeight();
            int margen = 40;
            int espacio = (ancho - margen * 2) / datos.size();
            int indice = 0;

            for (String nombre : datos.keySet()) {

                double valor = datos.get(nombre);

                int alturaBarra = (int) ((valor / maximo) * (alto - 90));

                int x = margen + indice * espacio;
                int y = alto - 45 - alturaBarra;

                g2.setColor(Color.BLUE);
                g2.fillRect(x + 10, y, espacio - 20, alturaBarra);

                g2.setColor(Color.BLACK);
                g2.drawString(
                        nombre,
                        x + 5,
                        alto - 25
                );

                g2.drawString(
                        String.format("L. %.2f", valor),
                        x + 5,
                        y - 5
                );

                indice++;
            }
        }
    }

    private class GraficoOrdenes extends JPanel {

        private Map<String, Integer> datos = new HashMap<>();

        public void setDatos(Map<String, Integer> datos) {
            this.datos = datos;
            repaint();
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);

            Graphics2D g2 = (Graphics2D) g;
            g2.setRenderingHint(
                    RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON
            );

            int ancho = getWidth();
            int alto = getHeight();
            int margen = 40;

            int maximo = 0;

            for (int cantidad : datos.values()) {
                if (cantidad > maximo) {
                    maximo = cantidad;
                }
            }

            if (maximo == 0) {
                g2.drawString("No hay órdenes registradas", 20, 30);
                return;
            }

            int espacio = (ancho - margen * 2) / datos.size();
            int indice = 0;

            for (String estado : datos.keySet()) {

                int cantidad = datos.get(estado);

                int alturaBarra = (int) (((double) cantidad / maximo) * (alto - 90));

                int x = margen + indice * espacio;
                int y = alto - 45 - alturaBarra;

                g2.setColor(Color.GREEN);
                g2.fillRect(x + 10, y, espacio - 20, alturaBarra);

                g2.setColor(Color.BLACK);
                g2.drawString(estado, x + 5, alto - 25);
                g2.drawString(String.valueOf(cantidad), x + 10, y - 5);

                indice++;
            }
        }
    }
