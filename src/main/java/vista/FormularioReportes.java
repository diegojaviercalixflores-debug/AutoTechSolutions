    private Map<String, Double> obtenerIngresosPorServicio() {

        Map<String, Double> ingresos = new HashMap<>();

        for (modelo.OrdenTrabajo orden : ordenController.listarOrdenes()) {

            if (orden.getEstado().equals("Finalizada")) {

                for (modelo.Servicio servicio : orden.getServicios()) {

                    String nombre = servicio.getDescripcion();

                    double precio = servicio.getPrecioBase();

                    double acumulado = ingresos.getOrDefault(nombre, 0.0);

                    ingresos.put(nombre, acumulado + precio);
                }
            }
        }

        return ingresos;
    }

    private Map<String, Integer> obtenerOrdenesPorEstado() {

        Map<String, Integer> cantidades = new HashMap<>();

        cantidades.put("Pendiente", 0);
        cantidades.put("En proceso", 0);
        cantidades.put("Finalizada", 0);
        cantidades.put("Cancelada", 0);

        for (modelo.OrdenTrabajo orden : ordenController.listarOrdenes()) {

            String estado = orden.getEstado();

            int cantidad = cantidades.getOrDefault(estado, 0);

            cantidades.put(estado, cantidad + 1);
        }

        return cantidades;
    }

    private void actualizarGraficos() {

        graficoIngresos.setDatos(obtenerIngresosPorServicio());

        graficoOrdenes.setDatos(obtenerOrdenesPorEstado());
    }

