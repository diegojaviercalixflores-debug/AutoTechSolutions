    private void btnEntradaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntradaActionPerformed
        // TODO add your handling code here:
        try {
            String codigo = txtCodigo.getText().trim();

            if (codigo.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Ingrese el código del repuesto");
                return;
            }

            Repuesto repuesto = repuestoController.buscarRepuesto(codigo);

            if (repuesto == null) {
                JOptionPane.showMessageDialog(this,
                        "El repuesto no existe");
                return;
            }

            String cantidadTexto = JOptionPane.showInputDialog(
                    this,
                    "Ingrese la cantidad que desea agregar:"
            );

            if (cantidadTexto == null) {
                return;
            }

            cantidadTexto = cantidadTexto.trim();

            if (cantidadTexto.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Ingrese una cantidad");
                return;
            }

            int cantidad = Integer.parseInt(cantidadTexto);

            repuestoController.registrarEntrada(codigo, cantidad);

            JOptionPane.showMessageDialog(this,
                    "Entrada registrada correctamente");

            limpiarCampos();
            cargarTabla();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese una cantidad numérica válida");
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnEntradaActionPerformed

