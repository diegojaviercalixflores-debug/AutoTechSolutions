    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaRepuestos.getModel();

        modelo.setRowCount(0);

        for (Repuesto repuesto : repuestoController.listarRepuestos()) {

            String estado = repuesto.getCantidad() <= repuesto.getStockMinimo()
                    ? "Stock bajo" : "Disponible";

            modelo.addRow(new Object[]{
                repuesto.getCodigo(),
                repuesto.getNombre(),
                repuesto.getCantidad(),
                repuesto.getPrecioUnitario(),
                repuesto.getStockMinimo(),
                estado
            });
        }
    }

