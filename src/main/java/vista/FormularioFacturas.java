    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        // TODO add your handling code here:
        String numeroFactura = txtNumeroFactura.getText();
        String numeroOrden = (String) cmbNumeroOrden.getSelectedItem();

        if (numeroOrden == null) {
            JOptionPane.showMessageDialog(this,
                    "No hay órdenes finalizadas para facturar");
            return;
        }

        if (txtImpuesto.getText().trim().isEmpty()
                || txtPago.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el impuesto y el pago recibido");
            return;
        }

        try {
            double impuesto = Double.parseDouble(txtImpuesto.getText());
            double pago = Double.parseDouble(txtPago.getText());

            if (impuesto < 0 || pago < 0) {
                JOptionPane.showMessageDialog(this,
                        "No se permiten valores negativos");
                return;
            }

            facturaController.generarFactura(
                    numeroFactura, numeroOrden, impuesto, pago);

            Factura factura = facturaController.buscarFactura(numeroFactura);

            txtCambio.setText(
                    String.format("L. %.2f", factura.getCambio()));

            JOptionPane.showMessageDialog(this,
                    "Factura generada correctamente");

            generarNumeroFactura();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese valores numéricos válidos");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnGenerarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        String numero = JOptionPane.showInputDialog(this,
                "Ingrese el número de la factura (FAC-001):",
                "Consultar factura",
                JOptionPane.QUESTION_MESSAGE);

        if (numero == null || numero.trim().isEmpty()) {
            return;
        }

        Factura factura = facturaController.buscarFactura(numero.trim());

        if (factura == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró la factura");
            return;
        }

        txtNumeroFactura.setText(factura.getNumero());

        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        txtFecha.setText(formato.format(factura.getFecha()));

        cmbNumeroOrden.setSelectedItem(factura.getOrden().getNumero());

        txtImpuesto.setText(String.valueOf(factura.getImpuesto()));
        txtPago.setText(String.format("%.2f", factura.getPago()));

        txtSubtotalServicios.setText(
                String.format("L. %.2f", factura.getSubtotalServicios()));

        txtSubtotalRepuestos.setText(
                String.format("L. %.2f", factura.getSubtotalRepuestos()));

        txtTotal.setText(String.format("L. %.2f", factura.getTotal()));

        txtCambio.setText(String.format("L. %.2f", factura.getCambio()));
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        // TODO add your handling code here:
        List<Factura> lista = facturaController.listarFacturas();

        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No hay facturas registradas");
            return;
        }

        String[] columnas = {
            "Número", "Fecha", "Orden", "Cliente",
            "Subtotal servicios", "Subtotal repuestos",
            "Impuesto", "Total", "Pago", "Cambio"
        };

        DefaultTableModel modelo = new DefaultTableModel(columnas, 0);

        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");

        for (Factura f : lista) {
            Object[] fila = {
                f.getNumero(),
                formato.format(f.getFecha()),
                f.getOrden().getNumero(),
                f.getOrden().getCliente().getNombreCompleto(),
                String.format("L. %.2f", f.getSubtotalServicios()),
                String.format("L. %.2f", f.getSubtotalRepuestos()),
                f.getImpuesto() + "%",
                String.format("L. %.2f", f.getTotal()),
                String.format("L. %.2f", f.getPago()),
                String.format("L. %.2f", f.getCambio())
            };

            modelo.addRow(fila);
        }

        JTable tabla = new JTable(modelo);
        JScrollPane scroll = new JScrollPane(tabla);
        scroll.setPreferredSize(new java.awt.Dimension(900, 300));

        JOptionPane.showMessageDialog(this, scroll,
                "Facturas registradas", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnListarActionPerformed

