    private void btnListarPorClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarPorClienteActionPerformed
        // TODO add your handling code here:
        try {
            String codigoCliente = txtCodigoCliente.getText().trim();

            if (codigoCliente.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese el código del cliente");
                return;
            }

            List<Vehiculo> vehiculos = vehiculoController.listarPorCliente(codigoCliente);

            DefaultTableModel modelo = (DefaultTableModel) tablaVehiculos.getModel();
            modelo.setRowCount(0);

            if (vehiculos.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Este cliente no tiene vehículos registrados");
                return;
            }

            for (Vehiculo vehiculo : vehiculos) {
                modelo.addRow(new Object[]{
                    vehiculo.getPlaca(),
                    vehiculo.getMarca(),
                    vehiculo.getModelo(),
                    vehiculo.getAnio(),
                    vehiculo.getColor(),
                    vehiculo.getPropietario().getCodigo()
                });
            }

        } catch (ClienteNoEncontradoException e) {
            JOptionPane.showMessageDialog(this, "El cliente indicado no existe");
        }
    }//GEN-LAST:event_btnListarPorClienteActionPerformed

