    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaVehiculos.getModel();

        modelo.setRowCount(0);

        List<Vehiculo> vehiculos = vehiculoController.listarVehiculos();

        for (Vehiculo vehiculo : vehiculos) {
            modelo.addRow(new Object[]{
                vehiculo.getPlaca(),
                vehiculo.getMarca(),
                vehiculo.getModelo(),
                vehiculo.getAnio(),
                vehiculo.getColor(),
                vehiculo.getPropietario().getCodigo()
            });
        }
    }

